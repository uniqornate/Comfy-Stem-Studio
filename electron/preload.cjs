const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('desktop', Object.freeze({
  getProject: () => ipcRenderer.invoke('project:get'),
  recentProjects: () => ipcRenderer.invoke('project:recent'),
  saveProject: payload => ipcRenderer.invoke('project:save', payload),
  projectAction: (action, payload, argument) => ipcRenderer.invoke('project:action', action, payload, argument),
  closeProject: payload => ipcRenderer.invoke('project:close', payload),
  onProjectClose: callback => { const listener = () => callback(); ipcRenderer.on('project:request-close', listener); return () => ipcRenderer.removeListener('project:request-close', listener); },
  samStatus: (profile, variant) => ipcRenderer.invoke('sam:status', profile, variant),
  prepareSAM: (profile, token, variant) => ipcRenderer.invoke('sam:prepare', profile, token, variant),
  cancelSAM: () => ipcRenderer.invoke('sam:cancel'),
  guidesepStatus: profile => ipcRenderer.invoke('guidesep:status', profile),
  prepareGuideSep: profile => ipcRenderer.invoke('guidesep:prepare', profile),
  cancelGuideSep: () => ipcRenderer.invoke('guidesep:cancel'),
  chooseReference: () => ipcRenderer.invoke('reference:choose'),
  brushStatus: profile => ipcRenderer.invoke('brush:status', profile),
  prepareBrush: profile => ipcRenderer.invoke('brush:prepare', profile),
  cancelBrush: () => ipcRenderer.invoke('brush:cancel'),
  chooseBatchFiles: () => ipcRenderer.invoke('batch:choose-files'),
  chooseBatchFolder: () => ipcRenderer.invoke('batch:choose-folder'),
  startBatch: (profile, files, options) => ipcRenderer.invoke('batch:start', profile, files, options),
  batchStatus: () => ipcRenderer.invoke('batch:status'),
  cancelBatch: () => ipcRenderer.invoke('batch:cancel'),
  exportMix: (profile, options) => ipcRenderer.invoke('mix:export', profile, options),
  cancelMix: () => ipcRenderer.invoke('mix:cancel'),
  resources: (profile) => ipcRenderer.invoke('resources:get', profile),
  setLayoutZoom: (factor) => ipcRenderer.invoke('layout:zoom', factor),
  exportVideo: (profile, options) => ipcRenderer.invoke('video:export', profile, options),
  exportStatus: () => ipcRenderer.invoke('video:export-status'),
  cancelExport: () => ipcRenderer.invoke('video:export-cancel'),
  getProfile: () => ipcRenderer.invoke('profile:get'),
  saveProfile: (profile) => ipcRenderer.invoke('profile:save', profile),
  checkConnection: (profile) => ipcRenderer.invoke('connection:check', profile),
  proxyStatus: () => ipcRenderer.invoke('proxy:status'),
  startProxy: (profile) => ipcRenderer.invoke('proxy:start', profile),
  stopProxy: () => ipcRenderer.invoke('proxy:stop'),
  checkEngine: (profile) => ipcRenderer.invoke('engine:check', profile),
  separateStems: (profile, sourceUrl, options) => ipcRenderer.invoke('stems:start', profile, sourceUrl, options),
  stemStatus: () => ipcRenderer.invoke('stems:status'),
  cancelSeparation: () => ipcRenderer.invoke('stems:cancel'),
  saveStem: (id, edits, profile) => ipcRenderer.invoke('stems:save', id, edits, profile),
  saveAllStems: (ids, edits, profile) => ipcRenderer.invoke('stems:save-all', ids, edits, profile),
  chooseInstallation: () => ipcRenderer.invoke('installation:choose'),
  openVideo: () => ipcRenderer.invoke('video:open'),
}));
